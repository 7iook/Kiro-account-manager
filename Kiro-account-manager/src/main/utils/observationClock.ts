/**
 * 观测版本戳 —— 用于给「同一份数据的多次并发观测」定**因果顺序**。
 *
 * ## 为什么不是 `Date.now()`
 *
 * 这个值唯一的用途是回答「两份数据哪个更新」。`Date.now()` 在这件事上有两个坑:
 *
 *   1. **不单调**。NTP 校正 / 用户改系统时间 / 虚拟机挂起恢复都能让它**往回跳**。
 *      往回跳一次,后发出的观测就会拿到更小的值,于是被判成「迟到的旧响应」而被丢弃 ——
 *      正是它本该防的那个后果。
 *   2. **分辨率不足**。同一毫秒内发出的两次观测拿到相同的值,顺序信息直接丢失。
 *
 * ## 为什么不是纯计数器
 *
 * 纯计数器(1, 2, 3...)在**新进程**里从头开始,而 `quotaUpdatedAt` 会跨整池重建被迁移
 * (`accountPool.ts:mergeRuntimeState`),盘上/池内可能已经存在**墙钟量级**的旧基线。
 * 一个从 1 开始的计数器永远小于它 ⇒ 所有新观测被当成迟到的旧响应,静默全丢。
 *
 * ## 采用:墙钟锚定的单调戳(Hybrid Logical Clock 的本地事件规则)
 *
 * `next = max(now, last + 1)` —— 既保持与墙钟同量级(所以能和迁移来的旧基线、
 * 与未参与排序的调用方留下的 `Date.now()` 直接比较),又保证**进程内严格单调递增**
 * (所以时钟回跳与同毫秒并发都不会丢顺序)。
 * 这是 CockroachDB / MongoDB / YugabyteDB 用来替代墙钟 last-write-wins 的同一条规则
 * (Kulkarni & Demirbas 2014;Martin Fowler «Hybrid Clock» 模式)。
 *
 * ## 它不是时间,不要当时间用
 *
 * 返回值**只可用于互相比较**。它可以比真实墙钟大(同毫秒并发时每次 +1),所以
 * **绝不可**拿去显示给用户、算时间差、或判断「多久之前」。
 * 需要「这份数据有多旧」的语义时,另存一个真实的 `Date.now()`。
 */

/**
 * 进程内最近一次发出的版本号。
 *
 * 单进程单调即已足够:这个值只在**主进程内部**产生与比较(账号池活在主进程内存里,
 * 不跨进程复制、不做多副本合并),所以不需要 HLC 的节点分量或向量时钟。
 */
let last = 0

/**
 * 取下一个观测版本号。**在观测被发起的那一刻调用**(即上游请求发出前),
 * 不是在结果落盘时 —— 后者记录的是完成顺序,而慢响应会晚于后发出的快响应完成,
 * 于是旧数据反而拿到更大的值并覆盖新数据。
 *
 * @param now 注入墙钟(仅供测试;生产用默认值)
 * @returns 严格大于此前所有返回值的版本号
 */
export function nextObservationVersion(now: number = Date.now()): number {
  last = now > last ? now : last + 1
  return last
}
